<script setup>
import { onMounted, ref } from 'vue'

import Map from 'ol/Map'
import View from 'ol/View'

// a good way of importing external framework CSS in modern JS is to add the CSS directly in the imports
// although many framework now do that for you (OL doesn't)
import 'ol/ol.css'
import {
    getSwisstopoWMSSingleImageLayer,
    getSwisstopoWMTSLayer,
} from './swisstopo/swisstopoLayerUtils'
import { identifyFeatures } from './swisstopo/swisstopoIdentifyUtils'
import FeatureList from './FeatureList.vue'

const features = ref([])

let map
// the mounted lifecycle hook is run after the component is added to the page
// it's the perfect place to link OpenLayers to our HTML generated by Vue
onMounted(() => {
    // we keep track of OpenLayers instance with this.map attribute
    // (will be useful later when we will want to add event listeners)
    map = new Map({
        layers: [
            // Switching from OSM layer to Swisstopo National map
            getSwisstopoWMTSLayer('ch.swisstopo.pixelkarte-farbe'),
            // Adding a second layer on top of the national map
            getSwisstopoWMSSingleImageLayer('ch.kantone.cadastralwebmap-farbe'),
        ],
        // this refers to the HTML ID of the div defined above in the template
        target: 'map',
        view: new View({
            // roughly the center of Switzerland
            center: [2660000, 1190000],
            // showing roughly the entire country
            zoom: 2,
            projection: 'EPSG:2056',
        }),
    })

    // registering an event handler on map click
    map.on('click', (event) => {
        // OpenLayers gives us where the click occured through the event
        const clickCoordinates = event.coordinate
        // the map's view can also give us the extent we are rendering (the area the map covers,
        // it is expressed as [bottom-left, top-right] coordinates)
        const mapExtent = map.getView().calculateExtent()
        // asking Swisstopo if there is some feature under the mouse cursor
        identifyFeatures(
            clickCoordinates,
            mapExtent,
            // it is mandatory to tell which layer we want to know if there is a feature
            'ch.kantone.cadastralwebmap-farbe'
        )
            // identifyFeatures returns a promise, we have to handle it through lambda functions
            // mapping response's results for ease of use later on
            .then((response) => response.data.results)
            .then((foundFeatures) => {
                features.value = [...foundFeatures]
            })
    })
})

// solution for the first step: checkout git branch "step-1"
// git checkout step-1
</script>

<template>
    <div id="map" />
    <FeatureList
        v-if="features.length > 0"
        class="position-absolute bottom-0 start-50 translate-middle-x"
        :features="features"
        @close="features = []"
    />
</template>

<style scoped>
/* placing the map relative to its parent, and taking the maximum space it can.
 Its parent is App.vue component, and it is set to take the whole page, so our 
 map will take the whole screen too */
#map {
    position: relative;
    width: 100%;
    height: 100%;
}
</style>
